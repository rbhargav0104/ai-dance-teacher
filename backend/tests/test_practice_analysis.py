"""Learner attempts through the REAL pipeline (Outcome 5 exit gate, backend half).

Attempt videos are FFmpeg variants of real Mixkit footage (fixtures/attempts, generated by
scripts/make_attempt_fixtures.py). Every landmark comes from MediaPipe; nothing is fabricated.
No comparison or scoring happens yet (Outcomes 6-7) — these tests check that learner pose is
measured with the same model, features and quality gates as the reference.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

import pytest
from fastapi.testclient import TestClient

from app.config import REPO_ROOT
from tests.test_reference_analysis import (  # noqa: F401 - fixtures
    auth,
    frame_rgb,
    is_green,
    real,
    run_jobs,
)

ATTEMPTS = REPO_ROOT / "fixtures" / "attempts"
pytestmark = pytest.mark.skipif(not ATTEMPTS.is_dir(), reason="attempt fixtures missing")


def attempt(
    c: TestClient, headers: dict[str, str], pid: str, name: str, **fields: str
) -> dict[str, Any]:
    path = ATTEMPTS / f"{name}.mp4"
    with path.open("rb") as fh:
        res = c.post(
            f"/api/projects/{pid}/practice-sessions",
            headers=headers,
            files={"file": (path.name, fh, "video/mp4")},
            data=fields,
        )
    assert res.status_code == 201, res.text
    body: dict[str, Any] = res.json()
    return body


def analysed_girl(c: TestClient, headers: dict[str, str]) -> dict[str, Any]:
    res = c.post(
        "/api/projects/sample", headers=headers, json={"sample_id": "mixkit_girl_earphones_28306"}
    )
    assert res.status_code == 201, res.text
    assert run_jobs() == 1
    project: dict[str, Any] = c.get(f"/api/projects/{res.json()['id']}", headers=headers).json()
    assert project["status"] == "analyzed"
    return project


def test_learner_attempts_use_the_same_pipeline_and_gates(
    real: TestClient,  # noqa: F811
    auth: dict[str, str],  # noqa: F811
) -> None:
    project = analysed_girl(real, auth)
    pid = project["id"]
    ref_job = project["latest_job"]
    sections = real.get(f"/api/projects/{pid}/segments", headers=auth).json()["sections"]

    good = attempt(real, auth, pid, "girl_good", capture_source="upload")
    scaled = attempt(real, auth, pid, "girl_scaled_translated")
    occluded = attempt(real, auth, pid, "girl_occluded")
    section = attempt(real, auth, pid, "girl_good", segment_id=sections[0]["id"])
    # A READY server starts learner analysis straight away; re-requests are idempotent.
    assert good["status"] == "queued" and good["latest_job"]["kind"] == "practice_analysis"
    again = real.post(f"/api/practice-sessions/{good['id']}/analysis", headers=auth)
    assert again.status_code == 200 and again.json()["id"] == good["latest_job"]["id"]
    assert run_jobs() == 4

    # The dance itself is untouched: still analysed, its own latest job is the reference job.
    after = real.get(f"/api/projects/{pid}", headers=auth).json()
    assert after["status"] == "analyzed" and after["latest_job"]["id"] == ref_job["id"]

    got = {
        k: real.get(f"/api/practice-sessions/{a['id']}", headers=auth).json()
        for k, a in {
            "good": good,
            "scaled": scaled,
            "occluded": occluded,
            "section": section,
        }.items()
    }
    ref = project["reference"]
    for k, a in got.items():
        assert a["status"] == "analyzed", (k, a)
        assert a["latest_job"]["status"] == "succeeded"
        assert a["pipeline_version"] == "learner-pose-1"
        assert a["model_version"] == ref["model_version"]  # same model as the reference
        assert a["analysis_fps"] == ref["analysis_fps"] == 12.0
        assert (a["canonical_width"], a["canonical_height"]) == (640, 360)
        assert a["quality"]["thresholds"] == ref["quality"]["thresholds"]  # same gates
        assert a["quality"]["smoothing"] == ref["quality"]["smoothing"]
        assert a["scored"] is False
    assert got["section"]["target"]["segment_id"] == sections[0]["id"]
    full = got["good"]["target"]
    assert (full["segment_id"], full["title"], full["start"]) == (None, "Full dance", 0.0)
    assert full["end"] == pytest.approx(14.0, abs=0.05)

    # Same performance → same trackability as the reference (lower resolution, same body).
    assert abs(got["good"]["tracking_coverage"] - ref["pose_coverage"]) < 0.08
    assert "cropped_body" in got["good"]["warnings"]  # legs still out of frame: honest

    # Learner poses: measured, aligned with the learner's own pixels.
    poses = real.get(f"/api/practice-sessions/{good['id']}/poses", headers=auth).json()
    frames = poses["frames"]
    assert len(frames) == pytest.approx(14.0 * 12, abs=2)
    assert poses["pipeline_version"] == "learner-pose-1" and poses["width"] == 640
    from app.db.session import get_sessionmaker
    from app.models import PracticeSession
    from app.storage import get_storage

    with get_sessionmaker()() as db:
        row = db.get(PracticeSession, good["id"])
        assert row is not None and row.canonical_object_key
        canonical = get_storage().local_path(row.canonical_object_key)
    valid = [f for f in frames if f["valid"]]
    for f in valid[:: max(1, len(valid) // 6)]:
        lm = f["data"]["landmarks"]
        assert lm[0][1] < (lm[11][1] + lm[12][1]) / 2 < (lm[23][1] + lm[24][1]) / 2
        img = frame_rgb(canonical, f["t"], 640, 360)
        for a, b in ((11, 23), (12, 24)):
            x, y = (lm[a][0] + lm[b][0]) / 2, (lm[a][1] + lm[b][1]) / 2
            assert not is_green(img[int(y * 360), int(x * 640)]), (f["t"], x, y)

    # Smaller in frame → the measured torso scale shrinks with it (normalization input).
    # The picture is 0.6x, but the measured ratio is lower (~0.48 locally): in the full-frame
    # clip the hips sit on the bottom edge and MediaPipe places them differently than when the
    # same picture is padded. Recorded for Outcome 6 (normalization must not lean on hips alone).
    ratio = got["scaled"]["quality"]["torso_scale"] / got["good"]["quality"]["torso_scale"]
    assert 0.4 < ratio < 0.7, ratio

    # View blocked from 5 s to 8 s → those frames have no pose (masked, not guessed).
    occ = real.get(f"/api/practice-sessions/{occluded['id']}/poses", headers=auth).json()["frames"]
    hidden = [f for f in occ if 5.2 <= f["t"] <= 7.8]
    shown = [f for f in occ if f["t"] < 4.5 or f["t"] > 8.5]
    assert sum(not f["valid"] for f in hidden) >= 0.8 * len(hidden)
    assert sum(f["valid"] for f in shown) >= 0.8 * len(shown)
    assert got["occluded"]["tracking_coverage"] < got["good"]["tracking_coverage"] - 0.15
    assert "partial_coverage" in got["occluded"]["warnings"]

    media = real.get(f"/api/practice-sessions/{good['id']}/media/canonical", headers=auth).json()
    assert real.get(media["url"], headers={"Range": "bytes=0-99"}).status_code == 206


def test_wrong_dancer_count_fails_honestly_and_delete_while_queued(
    real: TestClient,  # noqa: F811
    auth: dict[str, str],  # noqa: F811
    tmp_path: Path,
) -> None:
    from tests.test_reference_analysis import BOY, GIRL, ffmpeg

    project = analysed_girl(real, auth)
    pid = project["id"]
    duo = tmp_path / "duo.mp4"
    ffmpeg(
        "-i", str(GIRL), "-i", str(BOY), "-filter_complex",
        "[0:v]crop=640:720[a];[1:v]crop=640:720[b];[a][b]hstack,scale=640:360", "-t", "6",
        "-an", "-c:v", "libx264", "-pix_fmt", "yuv420p", str(duo),
    )  # fmt: skip
    with duo.open("rb") as fh:
        res = real.post(
            f"/api/projects/{pid}/practice-sessions", headers=auth, files={"file": ("duo.mp4", fh)}
        )
    duo_id = res.json()["id"]
    queued = attempt(real, auth, pid, "girl_good")
    assert real.delete(f"/api/practice-sessions/{queued['id']}", headers=auth).status_code == 204
    assert run_jobs() == 1  # the deleted attempt's job went with it

    failed = real.get(f"/api/practice-sessions/{duo_id}", headers=auth).json()
    # A2: two people → "Who should we follow?" instead of a failure.
    assert failed["status"] == "needs_subject" and failed["error_code"] == "choose_dancer"
    assert failed["latest_job"]["retryable"] is False
    assert len(failed["subject"]["candidates"]) == 2
    q = real.get(f"/api/practice-sessions/{duo_id}/poses", headers=auth).json()
    assert q["quality"]["multi_person_fraction"] > 0.2  # still inspectable
    assert real.get(f"/api/projects/{pid}", headers=auth).json()["status"] == "analyzed"
